/* dump_distributions — emit all bench distribution histograms as a
 * JS-loadable data file for the figures/tree_viz.html visualization.
 *
 * Usage:
 *   ./build/pivco_dump_distributions > figures/tree_viz_data.js
 *
 * Output format (suitable for <script src=> from a file:// page):
 *
 *   window.PIVCO_DISTRIBUTIONS = [
 *     { "name": "proba80", "is_main": true, "freq": [n0, n1, ..., n255] },
 *     ...
 *   ];
 */

#include "pivco_huffman.h"

#include <stdint.h>
#include <stdio.h>

extern void            bench_init(void);
extern int             bench_num_distributions(void);
extern const char     *bench_dist_name(int idx);
extern const uint64_t *bench_dist_freq(int idx);
extern int             bench_dist_is_main(int idx);

int main(void)
{
    bench_init();
    int n_dist = bench_num_distributions();

    printf("/* Generated by extras/dump_distributions.  Do not edit by hand. */\n");
    printf("window.PIVCO_DISTRIBUTIONS = [\n");
    for (int d = 0; d < n_dist; d++) {
        const char *name = bench_dist_name(d);
        const uint64_t *f = bench_dist_freq(d);
        int is_main = bench_dist_is_main(d);

        printf("  { \"name\": \"%s\", \"is_main\": %s, \"freq\": [",
                name, is_main ? "true" : "false");
        for (int i = 0; i < 256; i++) {
            if (i > 0) printf(",");
            printf("%llu", (unsigned long long)f[i]);
        }
        printf("] }%s\n", d + 1 < n_dist ? "," : "");
    }
    printf("];\n");
    return 0;
}
