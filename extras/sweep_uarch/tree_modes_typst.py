#!/usr/bin/env python3
"""Read bench_tree_modes output for M4 + c8i and emit a typst table snippet.

Columns are the 4 tree modes (NAIVE -> FUSED -> CANONICAL_FLAT -> OPTIMIZED,
i.e. left-to-right increasing optimization).  Rows are the 2 hosts.  Each
cell is the geometric mean of decode MB/s across all distributions in the
input file.

Geomean is the right summary for "decode bandwidth across distributions":
arithmetic mean over-weights the high-bandwidth (skewed) datasets;
geomean weights each dataset equally on a log scale.

usage: tree_modes_typst.py m4=<path> c8i=<path>
"""
import os, re, sys
from math import exp, log, fsum

MODE_ORDER = ["NAIVE", "FUSED", "CANONICAL_FLAT", "OPTIMIZED"]
MODE_LABEL = {"NAIVE": "naive", "FUSED": "fused",
              "CANONICAL_FLAT": "canonical+flat", "OPTIMIZED": "optimized"}
HOST_LABEL = {"m4": "M4", "c8i": "c8i"}

ROW_RE = re.compile(r"^\s*(\S+)\s+(NAIVE|FUSED|CANONICAL_FLAT|OPTIMIZED)\s+"
                    r"(\d+)\s+(\d+\.\d+)\s+(\d+)")

def parse(path):
    out = {}  # mode -> [mbs values across dists]
    with open(path) as f:
        for line in f:
            m = ROW_RE.match(line)
            if not m: continue
            mode, mbs = m.group(2), float(m.group(3))
            out.setdefault(mode, []).append(mbs)
    return out

def geomean(xs):
    if not xs: return 0.0
    return exp(fsum(log(x) for x in xs) / len(xs))

def main():
    hosts = {}
    for arg in sys.argv[1:]:
        k, _, p = arg.partition("=")
        hosts[k] = parse(p)

    if not hosts:
        print("usage: tree_modes_typst.py m4=<m4.txt> c8i=<c8i.txt>", file=sys.stderr)
        sys.exit(1)

    cells = {}  # (host, mode) -> geomean MB/s
    for h, data in hosts.items():
        for mode in MODE_ORDER:
            cells[(h, mode)] = geomean(data.get(mode, []))

    # emit typst snippet
    print("// Geomean of decode MB/s across distributions, per (host, tree-mode).")
    print("// Source: results/tree_modes/, generated by")
    print("// extras/sweep_uarch/tree_modes_typst.py.")
    print("#figure(")
    print("  table(")
    print("    columns: 5,")
    print("    align: (col, _) => if col == 0 { left } else { right },")
    print("    table.header(")
    print('      [*Host*],')
    print("      " + ",  ".join(f"[*{MODE_LABEL[m]}*]" for m in MODE_ORDER) + ",")
    print("    ),")
    for h in sorted(hosts.keys(), key=lambda x: ["m4","c8i"].index(x)
                                                  if x in ("m4","c8i") else 99):
        cells_row = [f"[{cells[(h,m)]:.0f}]" for m in MODE_ORDER]
        print(f"    [*{HOST_LABEL.get(h, h)}*],  " + ",  ".join(cells_row) + ",")
    print("  ),")
    print("  caption: [Decode bandwidth (MB/s, geomean across "
          f"{len(next(iter(hosts.values()))['OPTIMIZED'])} test "
          "distributions) per tree-build mode.  "
          "*naive*: every symbol a singleton (pure canonical Huffman tree).  "
          "*fused*: D=1 sibling-pair leaf fusion.  "
          "*canonical+flat*: detect flat subtrees that naturally occur in the "
          "canonical tree.  "
          "*optimized*: reorganize code-length tiers to maximize flat-subtree "
          "coverage.  FSE off in all runs.],")
    print(")<tab-tree-modes>")

    # also dump the per-distribution CSV for the curious
    print("", file=sys.stderr)
    print("// per-distribution raw (MB/s), for reference:", file=sys.stderr)
    print("// host,dist," + ",".join(MODE_ORDER), file=sys.stderr)

if __name__ == "__main__":
    main()
