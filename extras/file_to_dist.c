/* file_to_dist — read a file, emit a byte-frequency distribution.
 *
 * Output formats:
 *   default        C-array suitable for pasting into bench_distributions.c
 *   --summary      one-line summary: total bytes, distinct bytes, entropy
 *   --csv          one row per byte: byte,count,probability
 *
 * Examples:
 *   pivco_file_to_dist /tmp/cat.html                # default C-array
 *   pivco_file_to_dist -n html_wiki /tmp/cat.html   # name the array
 *   pivco_file_to_dist --summary /tmp/cat.html
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>

static int  print_csv(uint64_t freq[256], uint64_t total);
static int  print_summary(uint64_t freq[256], uint64_t total);
static int  print_carray(uint64_t freq[256], const char *name);

int main(int argc, char **argv)
{
    const char *name = "X";
    int mode_csv = 0, mode_summary = 0;
    const char *path = NULL;

    for (int i = 1; i < argc; i++) {
        if      (!strcmp(argv[i], "--csv"))     mode_csv = 1;
        else if (!strcmp(argv[i], "--summary")) mode_summary = 1;
        else if (!strcmp(argv[i], "-n") && i + 1 < argc) name = argv[++i];
        else if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) {
            fprintf(stderr,
                    "usage: %s [--csv|--summary] [-n NAME] FILE\n"
                    "  default     emit C array (\"static const uint64_t freq_NAME[256] = ...;\")\n"
                    "  --csv       emit byte,count,probability rows\n"
                    "  --summary   emit one-line stats (total, distinct, entropy)\n",
                    argv[0]);
            return 0;
        } else {
            path = argv[i];
        }
    }
    if (!path) {
        fprintf(stderr, "missing FILE\n");
        return 2;
    }

    FILE *f = fopen(path, "rb");
    if (!f) { perror(path); return 2; }

    uint64_t freq[256] = {0};
    uint64_t total = 0;
    unsigned char buf[64 * 1024];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        for (size_t i = 0; i < n; i++) freq[buf[i]]++;
        total += n;
    }
    fclose(f);

    if (mode_csv)     return print_csv(freq, total);
    if (mode_summary) return print_summary(freq, total);
    return print_carray(freq, name);
}

static int print_csv(uint64_t freq[256], uint64_t total)
{
    printf("byte,count,prob\n");
    for (int b = 0; b < 256; b++) {
        if (freq[b] == 0) continue;
        printf("%d,%llu,%.10f\n", b, (unsigned long long)freq[b],
               total ? (double)freq[b] / (double)total : 0.0);
    }
    return 0;
}

static int print_summary(uint64_t freq[256], uint64_t total)
{
    int distinct = 0;
    double H = 0.0;
    for (int b = 0; b < 256; b++) {
        if (freq[b] == 0) continue;
        distinct++;
        double p = (double)freq[b] / (double)total;
        H -= p * log2(p);
    }
    printf("total=%llu  distinct=%d  entropy=%.3f bits/byte  (max=8.000)\n",
           (unsigned long long)total, distinct, H);
    return 0;
}

static int print_carray(uint64_t freq[256], const char *name)
{
    int distinct = 0;
    double H = 0.0;
    uint64_t total = 0;
    for (int b = 0; b < 256; b++) total += freq[b];
    for (int b = 0; b < 256; b++) {
        if (freq[b] == 0) continue;
        distinct++;
        double p = (double)freq[b] / (double)total;
        H -= p * log2(p);
    }
    printf("/* generated by pivco_file_to_dist */\n");
    printf("/* total=%llu  distinct=%d  entropy=%.3f bits/byte */\n",
           (unsigned long long)total, distinct, H);
    printf("static const uint64_t freq_%s[256] = {\n", name);
    for (int b = 0; b < 256; b++) {
        if (b % 8 == 0) printf("   ");
        printf(" %10llu,", (unsigned long long)freq[b]);
        if (b % 8 == 7) printf("  /* 0x%02x..0x%02x */\n", b - 7, b);
    }
    printf("};\n");
    return 0;
}
