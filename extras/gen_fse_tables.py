#!/usr/bin/env python3
"""Generate the static tables for partition bitmaps:
  - src/pivco_fse_tables.h:  sFSE's normalized counts
  - src/pivco_snph_tables.h: snPH's code lengths (see src/pivco_nph.h)

Each table targets an IID Bernoulli bit stream packed 8-at-a-time
into bytes.  Table i (1..50) is tuned for "frequent-bit probability"
p_i = 0.50 + (i-1)*0.01 -- a simple linear schedule from 0.50 to 0.99
in 0.01 steps.  (This replaced the old quarter-powers-of-two schedule,
which over-resolved the very-skewed top end and left gaps in the
moderate range, e.g. between 0.70 and 0.75.)

By convention, the "frequent bit" is 0 (the LEFT side of partition
bitmaps).  When the encoder finds the right side is the majority,
it XOR-flips the bitmap and sets bit 7 of the per-node marker; the
table contents are identical either way.

For byte value v with popcount k = number of 1-bits in v,
P(v) = (1 - p)^k * p^(8 - k).  Quantized to FSE normalized counts
that sum to 2^tableLog (tableLog = 12 -> sum = 4096).

snPH's table i models the same distribution with a Huffman code
instead: the length-limited (MAX_CODE_LEN) Huffman lengths of P(v), by
package-merge, ties broken by symbol value so the output is
deterministic.  The lengths are wire: a stream names its table by
index, so changing them changes how existing streams decode.

Both headers are generated; check them in.
"""

import os
from math import comb

TABLE_LOG = 12           # sum of normalized counts = 2^12 = 4096
MAX_CODE_LEN = 11        # PIVCO_MAX_CODE_LEN
TABLE_SIZE = 1 << TABLE_LOG
NUM_TABLES = 50          # table ids 1..50; id 0 = "no FSE"


def freq_for(i: int) -> float:
    """Frequent-bit probability for table i (i in 1..NUM_TABLES).

    Linear schedule: 0.50, 0.51, ..., 0.99 (uniform 0.01 spacing)."""
    return (49 + i) / 100.0


def byte_prob(p: float, v: int) -> float:
    """P(byte v) under IID Bernoulli with P(bit=0) = p."""
    k = bin(v).count("1")          # popcount
    return (1.0 - p) ** k * p ** (8 - k)


def normalize_counts(probs: list[float], total: int) -> list[int]:
    """Quantize 256 probabilities to integer counts summing to `total`.

    Strategy: largest-remainder.  Any symbol with prob > 0 gets at
    least count 1 (FSE_buildCTable will reject count = 0 on a symbol
    that we may actually emit).  We then re-balance by subtracting
    from the largest counts to keep the sum exact.
    """
    assert len(probs) == 256
    raw = [p * total for p in probs]
    floor = [int(x) for x in raw]
    frac = [(raw[v] - floor[v], v) for v in range(256)]

    # Lift any positive-prob symbol to at least 1 (FSE convention).
    counts = list(floor)
    deficit = 0
    for v in range(256):
        if probs[v] > 0 and counts[v] == 0:
            counts[v] = 1
            deficit += 1

    sum_floor = sum(counts)
    remainder = total - sum_floor

    if remainder >= 0:
        # Distribute the remainder to the largest fractional parts.
        frac.sort(reverse=True)
        for _, v in frac[:remainder]:
            counts[v] += 1
    else:
        # We over-allocated by lifting; take back from the largest.
        order = sorted(range(256), key=lambda v: counts[v], reverse=True)
        i = 0
        deficit = -remainder
        while deficit > 0:
            v = order[i % 256]
            if counts[v] > 1:
                counts[v] -= 1
                deficit -= 1
            i += 1

    assert sum(counts) == total, (sum(counts), total)
    assert all(c >= 0 for c in counts)
    return counts


def package_merge(weights: list[float], limit: int) -> list[int]:
    """Length-limited Huffman code lengths for weights (all > 0)."""
    n = len(weights)
    leaves = sorted(((w, (s,)) for s, w in enumerate(weights)),
                    key=lambda it: (it[0], it[1][0]))
    cur = list(leaves)
    for _ in range(limit - 1):
        packages = [(cur[i][0] + cur[i + 1][0], cur[i][1] + cur[i + 1][1])
                    for i in range(0, len(cur) - 1, 2)]
        # Stable sort: at equal weight a leaf precedes a package, and
        # leaves keep symbol order.
        cur = sorted(leaves + packages, key=lambda it: it[0])
    lens = [0] * n
    for _, syms in cur[:2 * n - 2]:
        for s in syms:
            lens[s] += 1
    return lens


def snph_lens(probs: list[float]) -> list[int]:
    lens = package_merge(probs, MAX_CODE_LEN)
    assert abs(sum(2.0 ** -l for l in lens) - 1.0) < 1e-12
    assert all(1 <= l <= MAX_CODE_LEN for l in lens)
    return lens


def emit_snph_header(path: str, tables: list[tuple[float, list[float], list[int]]]) -> None:
    """Write the generated snPH header."""
    with open(path, "w") as f:
        f.write("/* Auto-generated by extras/gen_fse_tables.py -- do not edit by hand. */\n")
        f.write("/* snPH's static inner tables: code lengths per sFSE table index (see\n"
                " * src/pivco_nph.h).  Wire: a stream names its table by index. */\n\n")
        f.write("#ifndef PIVCO_SNPH_TABLES_H\n#define PIVCO_SNPH_TABLES_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"/* PIVCO_SNPH_NUM_TABLES (pivco_nph.h) must be {len(tables)}. */\n")
        f.write("/* Indexed 1..PIVCO_SNPH_NUM_TABLES like pivco_fse_freq; slot 0 unused. */\n")
        f.write("static const uint8_t pivco_snph_lens[PIVCO_SNPH_NUM_TABLES + 1][256] = {\n")
        f.write("    { 0 },\n")
        for i, (p, probs, lens) in enumerate(tables, start=1):
            bits = sum(q * l for q, l in zip(probs, lens))
            f.write(f"    /* table {i:2d}: p = {p:.2f}, {bits:.3f} bits/byte */\n")
            f.write("    {\n")
            for row in range(0, 256, 32):
                f.write("        " + ",".join(f"{l:2d}" for l in lens[row:row + 32]) + ",\n")
            f.write("    },\n")
        f.write("};\n\n#endif  /* PIVCO_SNPH_TABLES_H */\n")


def emit_header(path: str, tables: list[tuple[float, list[int]]]) -> None:
    """Write the generated C header."""
    with open(path, "w") as f:
        f.write("/* Auto-generated by extras/gen_fse_tables.py -- do not edit by hand. */\n")
        f.write("/* See docs/FSE-V0.md for the design.  Schedule: linear p = 0.50..0.99 step 0.01. */\n\n")
        f.write("#ifndef PIVCO_FSE_TABLES_H\n")
        f.write("#define PIVCO_FSE_TABLES_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define PIVCO_FSE_NUM_TABLES   {NUM_TABLES}\n")
        f.write(f"#define PIVCO_FSE_TABLE_LOG    {TABLE_LOG}\n")
        f.write(f"#define PIVCO_FSE_MAX_SYMBOL   255\n\n")

        f.write(f"/* Frequent-bit (bit=0) probability per table, indexed 1..{NUM_TABLES}. */\n")
        f.write(f"static const float pivco_fse_freq[PIVCO_FSE_NUM_TABLES + 1] = {{\n")
        f.write("    0.0f,  /* slot 0 reserved (marker 0 = no FSE) */\n")
        for i, (p, _) in enumerate(tables, start=1):
            f.write(f"    {p:.9f}f,  /* table {i:2d}: 1-in-{1.0/(1.0 - p):8.4f} */\n")
        f.write("};\n\n")

        f.write(f"/* Normalized byte counts (sum = 2^{TABLE_LOG} = {TABLE_SIZE}) per table. */\n")
        f.write(f"static const short pivco_fse_norm[PIVCO_FSE_NUM_TABLES + 1][256] = {{\n")
        f.write("    /* slot 0 reserved */\n")
        f.write("    { 0 },\n")
        for i, (p, counts) in enumerate(tables, start=1):
            f.write(f"    /* table {i:2d}  freq={p:.6f}  1-in-{1.0/(1.0 - p):.3f} */\n")
            f.write("    {")
            for j in range(0, 256, 16):
                f.write("\n        ")
                f.write(", ".join(f"{c:4d}" for c in counts[j:j+16]))
                if j + 16 < 256:
                    f.write(",")
            f.write("\n    },\n")
        f.write("};\n\n")
        f.write("#endif  /* PIVCO_FSE_TABLES_H */\n")


def main() -> None:
    tables = []
    snph_tables = []
    for i in range(1, NUM_TABLES + 1):
        p = freq_for(i)
        probs = [byte_prob(p, v) for v in range(256)]
        counts = normalize_counts(probs, TABLE_SIZE)
        tables.append((p, counts))
        snph_tables.append((p, probs, snph_lens(probs)))

    # Repo-relative output path.
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(repo, "src", "pivco_fse_tables.h")
    emit_header(out, tables)
    print(f"wrote {out}")
    out = os.path.join(repo, "src", "pivco_snph_tables.h")
    emit_snph_header(out, snph_tables)
    print(f"wrote {out}")

    # Sanity print: highlight a few skewed tables.
    for i in (1, 25, 40, 50):
        p, counts = tables[i - 1]
        top = sorted(range(256), key=lambda v: -counts[v])[:5]
        print(f"  table {i:2d}: p={p:.4f}  top bytes (popcount low first):")
        for v in top:
            print(f"     0x{v:02x} (popcnt={bin(v).count('1')}): count={counts[v]}")


if __name__ == "__main__":
    main()
